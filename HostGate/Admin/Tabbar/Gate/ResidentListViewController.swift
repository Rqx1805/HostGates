    func tableView(_ tableView: UITableView, cellForRowAt indexPath: IndexPath) -> UITableViewCell {
        let cell = tableView.dequeueReusableCell(withIdentifier: "cell", for: indexPath) as! ResidentListCell
        
        cell.email.text = language == "en" ? "Email" : "البريد الإلكتروني"
        cell.buliding_no.text = language == "en" ? "Building Number" : "رقم المبنى"
        cell.unit_no.text = language == "en" ? "Unit/Floor Number" : "وحدة / رقم الطابق"
        
        var dict = NSDictionary()
        dict = response.object(at: indexPath.row) as! NSDictionary
        cell.emailLbl.text = dict.value(forKey: "email") as? String
        cell.buildNoLbl.text = dict.value(forKey: "building_number") as? String
        cell.unitNoLbl.text = dict.value(forKey: "unit_number") as? String
        cell.nameLbl.text = dict.value(forKey: "name") as? String
        cell.passBtn.tag = indexPath.row
        cell.passBtn.addTarget(self, action: #selector(HandleTap(_:)), for: .touchUpInside)
        cell.reverseBtn.tag = indexPath.row
        cell.reverseBtn.addTarget(self, action: #selector(HandleTap1(_:)), for: .touchUpInside)
        return cell
    }
    
